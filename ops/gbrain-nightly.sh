#!/usr/bin/env bash
#
# gbrain nightly cycle: builds the graph's links and timelines, runs the
# maintenance cycle, hygiene, doc2query and health checks, then runs the
# optional local hooks (link backfill, vault export). Meant to be started by
# a scheduler (a launchd agent or a cron job).
#
# The brain is on Postgres (multi-session): no need to close Claude Code,
# concurrent connections are handled by the server.
#
# Local settings: the file named by GBRAIN_NIGHTLY_ENV (default
# ~/.gbrain/nightly.env) is sourced when it exists, and every variable it sets
# is exported to the steps below. That is where the optional hooks and the
# prompt overrides live (DOC2QUERY_PROMPT_FILE, HYGIENE_PROMPT_FILE, ...).
#
set -uo pipefail

# launchd starts with a minimal PATH: add what gbrain needs
# (including ~/.bun/bin: the `gbrain` binary is a script that does `exec bun run …`)
export PATH="$HOME/.bun/bin:$HOME/.local/bin:/opt/homebrew/opt/postgresql@17/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin"

nightly_env="${GBRAIN_NIGHTLY_ENV:-$HOME/.gbrain/nightly.env}"
if [ -f "$nightly_env" ]; then
  set -a
  # shellcheck source=/dev/null
  . "$nightly_env"
  set +a
fi

LOG="$HOME/.gbrain/nightly.log"
mkdir -p "$HOME/.gbrain"

echo "" >> "$LOG"
echo "========== $(date '+%Y-%m-%d %H:%M:%S') — cycle nocturne gbrain ==========" >> "$LOG"

# 1. Extract links + timeline from the pages in the database (source of truth)
echo "--- gbrain extract all --source db ---" >> "$LOG"
gbrain extract all --source db >> "$LOG" 2>&1
echo "--- extract terminé (code $?) ---" >> "$LOG"

# 2. Full maintenance cycle: facts, consolidation, enrichment, re-embedding
#    of stale chunks, orphan scan, takes, purge…
#
#    DELIBERATELY WITHOUT --dir (checked 2026-08-06): since the Postgres
#    migration, the markdown folder is no longer the source of truth but an
#    EXPORT regenerated by the export hook of step 4. Passing --dir turns on
#    the filesystem phases (lint, backlinks, sync, synthesize, patterns),
#    which would write into that export: their fixes would never reach the
#    database and would be erased by the next export → silent divergence.
#    The link graph is already complete in the database (extract, step 1);
#    the "missing backlinks" reported by check-backlinks are only textual
#    reciprocity in the .md files, not missing edges.
echo "--- gbrain dream ---" >> "$LOG"
gbrain dream >> "$LOG" 2>&1
echo "--- dream terminé (code $?) ---" >> "$LOG"

# 2b. Hygiene: freshness indicator, then Claude Code refreshes the summaries
#     that lag the most behind their timeline (5 pages at most, originals
#     excluded). Added 2026-10-21; details and log in
#     ops/hygiene/refresh-stale.sh and ~/.gbrain/hygiene/.
echo "--- hygiène (fraîcheur + rafraîchissement des synthèses) ---" >> "$LOG"
"$(dirname "$0")/hygiene/refresh-stale.sh" >> "$LOG" 2>&1
echo "--- hygiène terminée (code $?) ---" >> "$LOG"

# 2d. doc2query: questions generated by Claude Haiku (claude -p) for the
#     chunks of pages of 3 chunks or more that have none yet for their
#     current text (pages created or changed by the scheduled sync, the
#     dream and the hygiene above), then imported into gbrain, which
#     re-embeds and recomputes the keyword vectors of the touched chunks
#     only. Runs only when the setting is on (gbrain config set
#     search.chunk_index_text d2q); capped at 40 calls per night to protect
#     the quota. Added 2026-10-23; details in ops/doc2query/README.md, JSONL
#     and call log in ~/.gbrain/doc2query/.
if [ "$(gbrain config get search.chunk_index_text 2>/dev/null)" = "d2q" ]; then
  echo "--- doc2query ---" >> "$LOG"
  /usr/bin/python3 -I "$(dirname "$0")/doc2query/generate.py" --max-calls 40 >> "$LOG" 2>&1
  echo "--- doc2query terminé (code $?) ---" >> "$LOG"
fi

# 2e. Truth maintenance, Sundays only: detection of stale pages among the
#     pairs where one page changed during the week (read-only on the
#     database, judged by claude -p, at most 25 pairs per stage). Writes a
#     PROPOSAL into ~/.gbrain/health/truth/<date>/; nothing is applied to
#     the brain without the owner's review. Added 2026-10-23.
if [ "$(date +%u)" = 7 ]; then
  echo "--- maintien de la vérité (proposition hebdomadaire) ---" >> "$LOG"
  "$(dirname "$0")/truth/weekly-detect.sh" --max-judge 25 >> "$LOG" 2>&1
  echo "--- maintien de la vérité terminé (code $?) ---" >> "$LOG"
fi

# 2c. Brain health: daily report (usage, latency, errors, ratings, content,
#     freshness) and alerts; on Sundays, the 107-question bench and a replay
#     of the week's real searches. Added 2026-10-21; reports in
#     ~/.gbrain/health/.
echo "--- santé du brain ---" >> "$LOG"
if [ "$(date +%u)" = 7 ]; then
  "$(dirname "$0")/health/weekly.sh" >> "$LOG" 2>&1
fi
"$(dirname "$0")/health/health.sh" >> "$LOG" 2>&1
echo "--- santé terminée (code $?) ---" >> "$LOG"

# 3. Optional local hook: attach the meetings that arrived without links.
#
#    GBRAIN_NIGHTLY_LINK_BACKFILL_CMD, when set, is a command line run with
#    bash (skipped when unset). Use case: meeting notes ingested with no
#    wikilink in their body, while gbrain derives nothing from the
#    frontmatter, so every new meeting arrives orphaned; the hook turns
#    participants into `attended` links and tags into `discusses` links. It
#    should be idempotent, and it runs BEFORE the export so that the export
#    reflects the new links the same night.
if [ -n "${GBRAIN_NIGHTLY_LINK_BACKFILL_CMD:-}" ]; then
  echo "--- backfill liens meetings ---" >> "$LOG"
  bash -c "$GBRAIN_NIGHTLY_LINK_BACKFILL_CMD" >> "$LOG" 2>&1
  echo "--- backfill terminé (code $?) ---" >> "$LOG"
fi

# 4. Optional local hook: export the pages to a markdown vault (e.g. Obsidian)
#    so that it reflects the new and updated pages on disk.
#    GBRAIN_NIGHTLY_EXPORT_CMD, when set, is a command line run with bash
#    (skipped when unset).
if [ -n "${GBRAIN_NIGHTLY_EXPORT_CMD:-}" ]; then
  echo "--- sync Obsidian (export-pages.py all) ---" >> "$LOG"
  bash -c "$GBRAIN_NIGHTLY_EXPORT_CMD" >> "$LOG" 2>&1
fi

echo "========== fin $(date '+%Y-%m-%d %H:%M:%S') ==========" >> "$LOG"
